"""GA8 + GA4 (in-process part) + G-c: the normative vectors reproduce through production code.

- VG-0 (q-1 quantization) and VG-R (field-specific requirements): the frozen Gate 0 r3 vector files
  (byte-identical copies, ``data/SOURCES.sha256``) against ``velith.geometry.rules`` and
  ``velith.api.geometry_contract``.
- VG-1..VG-12: one vector per ``G0-BENCH-01`` case, generated by ``make_vg_vectors.py`` and pinned
  here; they run the real isolated worker.
"""

from __future__ import annotations

import json
from typing import Any

import pytest

from tests.geometry._cases import CASES, DATA, payload
from velith.api.geometry_contract import (
    GeometryEngineeringResult,
    GeometryTask,
    RequirementError,
    StepArtifact,
    facts_hash,
    parse_count,
    parse_length,
    parse_tolerance,
)
from velith.geometry import rules
from velith.geometry.verifier import GeometryVerifier


def _load(name: str) -> Any:
    return json.loads((DATA / name).read_text(encoding="utf-8"))


VG0 = _load("VG0_quantization_vectors_r3.json")["vectors"]
VGR = _load("VGR_requirement_vectors_r3.json")
VG = _load("vg_vectors.json")["vectors"]


@pytest.mark.parametrize("vector", VG0, ids=lambda v: f"{v['kind']}:{v['input_repr']}")
def test_vg0_quantization(vector: dict[str, str]) -> None:
    if "input_hex" in vector:
        assert (
            rules.quantize(float.fromhex(vector["input_hex"]), vector["kind"]) == vector["expected"]
        )
    else:
        assert vector["expected"] == "REJECTED"
        with pytest.raises(ValueError):
            rules.quantize(float(vector["input_repr"]), vector["kind"])


def _parsed(parser: Any, text: str) -> str:
    try:
        return str(parser(text, "x"))
    except RequirementError:
        return "REJECTED"


@pytest.mark.parametrize(
    ("group", "parser"),
    [("length", parse_length), ("tolerance", parse_tolerance), ("count", parse_count)],
)
def test_vgr_field_vectors(group: str, parser: Any) -> None:
    for vector in VGR[group]:
        assert _parsed(parser, vector["input"]) == vector["expected"], vector


def test_vgr_inch_derived_and_exact_comparison() -> None:
    for vector in VGR["inch_derived"]:
        assert _parsed(parse_length, vector["mm_exact"]) == vector["expected"]
    for vector in VGR["compare_within"]:
        assert (
            rules.within(vector["measured"], vector["nominal"], vector["tol"]) is vector["expected"]
        )


@pytest.mark.parametrize("case", list(CASES))
def test_vg_benchmark_vectors(case: str, verifier: GeometryVerifier) -> None:
    stem, declared, _expected, _failing = CASES[case]
    pinned = VG[case]
    artifact = StepArtifact(payload=payload(stem))
    assert artifact.content_hash == pinned["artifact"]
    outcome = verifier.evaluate(GeometryTask(task_id=case, requirements=declared), artifact)
    if pinned["outcome"] == "VERIFIED":
        assert isinstance(outcome, GeometryEngineeringResult)
        assert outcome.geometry_facts.content_hash == pinned["facts_hash"]
        assert outcome.content_hash == pinned["content_hash"]
        assert outcome.result_id == pinned["result_id"]
    else:
        assert not isinstance(outcome, GeometryEngineeringResult)
        assert outcome.reason.value == pinned["outcome"]
        assert (facts_hash(outcome.facts) if outcome.facts else None) == pinned["facts_hash"]
